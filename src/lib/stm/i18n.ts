const dicts: Record<Lang, Record<MsgKey, string>> = { de, en };

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
    let text = dicts[lang]?.[key] ?? de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
    return text;
}

export function isLang(v: unknown): v is Lang {
    return v === "de" || v === "en";
}

/** Decimal comma for German, point for English. */
export function formatNumber(lang: Lang, n: number, digits?: number) {
    const s = digits === undefined ? String(Math.round(n * 1000) / 1000) : n.toFixed(digits);
    return lang === "de" ? s.replace(".", ",") : s;
}
